def load_upstream(case):
    argv = [sys.executable, '-X', 'utf8', '-m', 'intent_demand', case]
    if case == 'revise-to-self-service':
        # Synthetic subsequent revision generated by the actual upstream functions.
        argv = [sys.executable, '-X', 'utf8', '-c', """from dataclasses import asdict, replace
import json
from intent_demand.context import TaskContext
from intent_demand.priority import compare
from intent_demand.handoff import choose
c=TaskContext(task_id='sample-home-scan', revision=3, statement='这次用手机试扫', batch='两页', deadline='今天', phone_available=True, phone_capture_accepted=True)
a=compare(c, 'delivery', 'try_this_batch')
print(json.dumps({'comparison':asdict(a),'decision':asdict(choose(c,a,'phone'))}, ensure_ascii=False))"""]
    p = subprocess.run(argv, cwd=UPSTREAM, capture_output=True, timeout=30, check=True)
    return json.loads(p.stdout.decode('utf8'))

def fingerprint(obj):
    return hashlib.sha256(json.dumps(obj, sort_keys=True, ensure_ascii=False, separators=(',', ':')).encode()).hexdigest()

class Entry:
    """Single active research session, with routing metadata, not a second field store.

    Inputs are synthetic upstream envelopes only, not authenticated production handoffs.
    Topic selection and draft receipt cannot modify the shopping state.
    """
    def __init__(self):
        self.state = new_dialogue(); self.mode = 'inactive'; self.draft = None
        self.focus = None; self.binding = None; self.seen = {}; self.notice = '尚未开始购物研究。'

    def _invalidate(self, message):
        self.state = new_dialogue(); self.focus = None; self.draft = None; self.binding = None
        self.mode = 'inactive'; self.notice = message

    def receive(self, envelope):
        # Reject unbound, malformed or conflicting versions before changing state.
        c = envelope['comparison']; ctx = c['context']; dec = envelope['decision']; route = dec['route']
        task, rev = ctx['task_id'], ctx['revision']
        if not isinstance(task, str) or not task or type(rev) is not int or rev < 1:
            raise ValueError('无有效任务版本')
        if route not in ('shopping_research', 'self_service', 'verify_conditions', 'deferred'):
            raise ValueError('未知路线')
        draft = dec.get('shopping_handoff')
        if route == 'shopping_research':
            direction = next((d for d in c['directions'] if d['key']=='device'), None)
            if not isinstance(draft, dict) or not direction or direction['status']!='available':
                raise ValueError('无有效设备研究选择')
            required = {'task_id':task,'revision':rev,'selected_need':c['need']['key'],'outcome':c['need']['outcome'],'selected_direction':'device','category':None,'scope':'read_only_product_research'}
            if any(draft.get(k)!=v for k,v in required.items()) or not isinstance(draft.get('confirmed_context'),dict) or not isinstance(draft.get('pending'),list):
                raise ValueError('草案与选择或版本不一致')
            if any(k not in ctx or ctx[k]!=v for k,v in draft['confirmed_context'].items()):
                raise ValueError('草案情境与上游记录冲突')
        elif draft is not None:
            raise ValueError('非购物路线不能携带购物草案')
        digest = fingerprint({'comparison':c,'decision':dec}); previous = self.seen.get(task)
        if previous:
            oldrev, olddigest = previous
            if rev < oldrev: raise ValueError('旧版本不能恢复旧购物结果')
            if rev == oldrev:
                if digest != olddigest: raise ValueError('同版本内容冲突，需上游新修订')
                return 'duplicate'  # no mutation; no resurrection after withdrawal/direct entry
        self._invalidate('采用新版本；旧研究不再作为当前依据。' if previous or self.mode!='inactive' else '已接收上游只读草案。')
        self.seen[task]=(rev,digest)
        if route == 'shopping_research':
            self.draft=deepcopy(draft); self.binding=(task,rev,digest); self.mode='handoff'
        else:
            self.notice += ' 非购物路线：'+route+'；'+dec['next_step']
        return route

    def direct(self):
        self._invalidate('直接购物研究；不要求上游草案。'); self.mode='direct'

    def withdraw(self):
        self._invalidate('已撤回购物研究；旧结果不再有效，重复草案不会恢复。')

    def select_topic(self, field):
        if self.mode=='inactive' or confirmed_values(self.state).get('category')!='printer' or 'usage' not in confirmed_values(self.state):
            raise ValueError('先由本人确认打印机品类和用途')
        if field is not None and field not in TOPICS:
            raise ValueError('未知关注点')
        self.focus=field

    def view(self):
        if self.mode=='inactive':
            return {'active':False,'notice':self.notice,'confirmed':{},'question':'','field':'','facts':[],'usage_research':None,'safe':dict.fromkeys(SAFE,False)}
        v=render_chat(deepcopy(self.state)); report=json.loads(v['report_json']); c=json.loads(v.get('cognition_context_json','{}'))
        if not all(report[k] is False for k in SAFE): raise ValueError('unexpected authority')
        field=self.focus or v['prompt_field']; question=QUESTION[field] if self.focus else v['prompt']
        return {'active':True,'notice':self.notice,'binding':self.binding,'draft':deepcopy(self.draft),'confirmed':confirmed_values(self.state),'deferred':report['deferred_fields'],'withdrawn':report['withdrawn_fields'],'field':field,'question':question,'base_field':v['prompt_field'],'base_question':v['prompt'],'choices':REFS.get(field,[]),'facts':c.get('candidate_facts',[]),'usage_research':c.get('usage_research'),'public_decision':report['public_decision'] or (report.get('cognition_comparison') or {}).get('public'),'result':v['result_text'],'safe':{k:report[k] for k in SAFE}}

    def answer(self, text):
        v=self.view(); field=v['field']
        if not v['active'] or not field: raise ValueError('没有当前问题')
        old_category=confirmed_values(self.state).get('category')
        self.state=submit_message(deepcopy(self.state),field,text); self.focus=None
        if field=='category' and old_category is not None and confirmed_values(self.state).get('category')!=old_category:
            self.notice='已换品类；旧打印机研究条件及现行比较失效。'
        return self.view()

    def change_category(self, text):
        if self.mode=='inactive': raise ValueError('没有现行研究')
        self.state=submit_message(deepcopy(self.state),'category',text);self.focus=None
        self.notice='本人明确更换研究品类；旧比较不作为当前依据。'
        return self.view()

    def use_draft_goal(self):
        # UI button copies text into an input box, not into confirmed fields.
        if self.draft is None or self.view()['field']!='usage': raise ValueError('仅在本人确认用途时可填入草稿')
        return self.draft['outcome']


