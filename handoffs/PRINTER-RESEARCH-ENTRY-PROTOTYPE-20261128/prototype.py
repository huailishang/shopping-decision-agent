    frame=ttk.Frame(root,padding=16);frame.pack(fill='both',expand=True)
    ttk.Label(frame,text='从解决问题到研究商品',font=('Microsoft YaHei UI',18,'bold')).pack(anchor='w')
    ttk.Label(frame,text='合成样例 · 不联网、不下单 · 上游线索不是已确认硬条件').pack(anchor='w',pady=(0,12))
    bar=ttk.Frame(frame);bar.pack(fill='x');ttk.Combobox(bar,textvariable=mode,values=['device-research','self-service','undecided','revise','revise-to-self-service'],state='readonly',width=20).pack(side='left')
    def act(fn):
        try: fn(); refresh()
        except Exception as exc: messagebox.showwarning('未执行',str(exc))
    load_button=ttk.Button(bar,text='载入上游合成样例',command=lambda:act(lambda:(entry.receive(load_upstream(mode.get())),answer.set(''))));load_button.pack(side='left',padx=5)
    ttk.Button(bar,text='直接购物研究',command=lambda:act(lambda:(entry.direct(),answer.set('')))).pack(side='left',padx=5)
    ttk.Button(bar,text='撤回研究',command=lambda:act(lambda:(entry.withdraw(),answer.set('')))).pack(side='left',padx=5)
    summary=tk.Text(frame,height=8,wrap='word',font=('Microsoft YaHei UI',10));summary.pack(fill='x',pady=8)
    focusbar=ttk.Frame(frame);focusbar.pack(fill='x');ttk.Label(focusbar,text='问错方向？换一个当前问题：').pack(side='left')
    labels={'自动提问（原入口）':None,**{v:k for k,v in TOPICS.items()}}
    combo=ttk.Combobox(focusbar,textvariable=topic,values=list(labels),state='readonly',width=29);combo.pack(side='left',padx=5)
    combo.bind('<<ComboboxSelected>>',lambda ev:act(lambda:(entry.select_topic(labels[topic.get()]),answer.set(''))))
    question=ttk.Label(frame,text='',wraplength=980,font=('Microsoft YaHei UI',12,'bold'));question.pack(anchor='w',pady=8)
    refs=ttk.Frame(frame);refs.pack(fill='x'); inputbar=ttk.Frame(frame);inputbar.pack(fill='x',pady=6)
    ttk.Entry(inputbar,textvariable=answer).pack(side='left',fill='x',expand=True)
    send_button=ttk.Button(inputbar,text='本人明确发送',command=lambda:act(lambda:(entry.answer(answer.get()),answer.set(''))));send_button.pack(side='left',padx=4)
    draft_button=ttk.Button(inputbar,text='填入上游目标（仅草稿）',command=lambda:act(lambda:answer.set(entry.use_draft_goal())));draft_button.pack(side='left',padx=4)
    ttk.Button(inputbar,text='更换品类（使用输入框）',command=lambda:act(lambda:(entry.change_category(answer.get()),answer.set('')))).pack(side='left')
    result=tk.Text(frame,wrap='word',font=('Microsoft YaHei UI',10));result.pack(fill='both',expand=True,pady=8)
    def put(widget,text):
        widget.configure(state='normal');widget.delete('1.0','end');widget.insert('end',text);widget.configure(state='disabled')
    def refresh():
        v=entry.view(); draft=v.get('draft'); topic.set(TOPICS.get(entry.focus,'自动提问（原入口）'))
        put(summary,v['notice']+'\n'+('上游目标：'+draft['outcome']+'\n情境：'+json.dumps(draft['confirmed_context'],ensure_ascii=False)+'\n待核：'+'、'.join(draft['pending'])+'\n' if draft else '')+'本人确认：'+json.dumps(v['confirmed'],ensure_ascii=False)+'\n暂缓：'+str(v.get('deferred',[]))+'；撤回：'+str(v.get('withdrawn',[])))
        combo.configure(state='readonly' if v['confirmed'].get('category')=='printer' and 'usage' in v['confirmed'] else 'disabled')
